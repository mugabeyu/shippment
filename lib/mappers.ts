export function mapShipment(row: any) {
  const lineItems = (row.line_items || row.shipment_line_items || []).map((li: any) => ({
    id: li.id,
    shipmentId: li.shipment_id,
    shippingItemId: li.shipping_item_id,
    itemName: li.item_name,
    categoryName: li.category_name,
    quantity: li.quantity,
    weightKg: li.weight_kg,
    unitPrice: li.unit_price,
    lineTotal: li.line_total,
    createdAt: li.created_at,
  }));

  return {
    id: row.id,
    idNo: row.id_no,
    trackingNumber: row.tracking_number,
    customerId: row.customer_id,
    origin: row.origin || 'Mauritius',
    destination: row.destination || 'Madagascar',
    category: row.category || '',
    weightKg: row.weight_kg,
    quantity: row.quantity,
    description: row.description,
    status: row.status,
    date: row.date,
    paymentStatus: row.payment_status,
    paymentMethod: row.payment_method,
    receiptSent: row.receipt_sent,
    pickupDate: row.pickup_date,
    expectedArrival: row.expected_arrival,
    insurance: row.insurance,
    specialInstructions: row.special_instructions,
    internalNotes: row.internal_notes,
    photos: row.photos,
    basePrice: row.base_price,
    discountAmount: row.discount_amount,
    finalAmount: row.final_amount,
    initialPayment: row.initial_payment ?? 0,
    balanceDue: Math.max(0, (row.final_amount ?? 0) - (row.initial_payment ?? 0)),
    shippingItemId: row.shipping_item_id,
    routeDirection: row.route_direction,
    createdBy: row.created_by ?? null,
    workSessionId: row.work_session_id ?? null,
    lineItems,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
    customer: row.customer ? {
      id: row.customer.id,
      name: row.customer.name,
      phone: row.customer.phone,
      email: row.customer.email,
      address: row.customer.address,
      photo: row.customer.photo,
      totalKgSent: row.customer.total_kg_sent,
      active: row.customer.active
    } : undefined
  };
}
